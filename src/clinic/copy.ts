export function readingFor(lang: Lang, flag: Flag): string {
  if (flag === 'green') return t(lang, 'readingGreen');
  if (flag === 'yellow') return t(lang, 'readingYellow');
  if (flag === 'red') return t(lang, 'readingRed');
  return t(lang, 'readingNone');
}

export function flagLabel(lang: Lang, flag: Flag): string {
  return t(lang, flag);
}
